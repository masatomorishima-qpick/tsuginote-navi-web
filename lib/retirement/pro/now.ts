/**
 * `Asia/Tokyo` の年（例：2026）。
 *
 * **`now` に既定値はありません。**呼び出し側が `new Date()` を渡してください。
 */
export function tokyoYear(now: Date): number {
  return Number(
    new Intl.DateTimeFormat('en-CA', { timeZone: 'Asia/Tokyo', year: 'numeric' }).format(now),
  );
}
